def get_campus_situation():
    now = datetime.now()
    current_month = now.month
    current_day = now.day

    if current_day <= 10:
        period = "초"
    elif current_day <= 20:
        period = "중순"
    else:
        period = "말"

    sem1_start = datetime(now.year, 3, 2)
    sem2_start = datetime(now.year, 8, 31)

    if sem1_start.date() <= now.date() <= datetime(now.year, 6, 21).date():
        days_passed = (now.date() - sem1_start.date()).days
        week_num = min((days_passed // 7) + 1, 16)
        weekly_vibe = WEEKLY_ACADEMIC_CONTEXT.get(week_num, "학기 중 바쁜 일상을 보내는 주간")
        seasonal_vibe = SEASONAL_MONTH_CONTEXT.get(current_month, f"{current_month}월의 캠퍼스")
        current_situation = f"[1학기 {week_num}주차] 학사일정상 '{weekly_vibe}'이며, 계절적으로는 '{seasonal_vibe}'입니다."

    elif sem2_start.date() <= now.date() <= datetime(now.year, 12, 20).date():
        days_passed = (now.date() - sem2_start.date()).days
        week_num = min((days_passed // 7) + 1, 16)
        weekly_vibe = WEEKLY_ACADEMIC_CONTEXT.get(week_num, "학기 중 바쁜 일상을 보내는 주간")
        seasonal_vibe = SEASONAL_MONTH_CONTEXT.get(current_month, f"{current_month}월의 캠퍼스")
        current_situation = f"[2학기 {week_num}주차] 학사일정상 '{weekly_vibe}'이며, 계절적으로는 '{seasonal_vibe}'입니다."

    else:
        seasonal_vibe = SEASONAL_MONTH_CONTEXT.get(current_month, "")
        current_situation = f"현재는 방학입니다. {seasonal_vibe} 푹 쉬거나 계절학기, 알바, 캠프 등으로 각자의 일상을 보내는 시기입니다."

    return current_month, period, current_situation


