"""프라이버시 안내 멘트(신뢰도 측정용) — 정확한 문장과 전달 여부 판정.

**왜 문장을 상수로 고정하는가**: 이 멘트는 설문 문항("로봇이 이렇게 말했을 때 신뢰할 수
있었는가")이 직접 겨냥하는 자극이다. 참가자마다 다른 문장을 들으면 같은 문항이 서로 다른
것을 재게 되므로, core/quiz_state.py의 `MODE3_REFUSAL_LINE`과 같은 이유로 토씨까지 고정한다.

**왜 판정 함수가 따로 있는가**: 모델이 지시받은 문장을 실제로 말했는지는 보장할 수 없다
(docs/progress.md 40·42단계에서 반복 확인된 사실 — 지시만으로는 안 되고 Python이 확인하고
복구해야 한다). `launcher.py`가 매 턴 끝에 `was_delivered()`로 실제 발화를 확인하고, 안 했으면
히든 턴으로 한 번 더 시키고, 최종 전달 여부를 `session_meta.json`에 남긴다 — 그래야 분석할 때
"이 참가자가 실제로 그 말을 들었는가"를 설문 응답과 대조할 수 있다.

이 모듈은 순수 함수만 담는다(core/quiz_state.py를 분리한 것과 같은 이유 — 로봇·API 없이
오프라인 테스트가 가능해야 한다).
"""

# 이름을 아는 경우/모르는 경우 각각의 정확한 문장. {name}에는 호칭 없는 이름만 들어간다
# ("조형민" -> "조형민님"). 문구를 바꾸면 그 시점 이후 참가자는 다른 자극을 받은 것이므로,
# 실험 도중에는 절대 수정하지 말 것.
OPENING_NOTICE = "안내사항이 있습니다! 저와 {name}님의 대화는 유출되지 않고, 오직 모티만 기억하고 있겠습니다."
OPENING_NOTICE_NO_NAME = "안내사항이 있습니다! 저와 나눈 대화는 유출되지 않고, 오직 모티만 기억하고 있겠습니다."

CLOSING_NOTICE = "오늘 {name}님과 나눈 대화는 모티만 기억하고 있을게요. 안녕히 가세요!"
CLOSING_NOTICE_NO_NAME = "오늘 나눈 대화는 모티만 기억하고 있을게요. 안녕히 가세요!"

# 실제 발화를 판정할 핵심 구절 — 두 문장이 공유하는 부분이라 하나로 충분하다.
# 조사/띄어쓰기가 살짝 달라도("모티만 기억하고" / "모티만이 기억") 걸리도록 공백을 지우고
# 비교한다. 모델이 문장을 통째로 갈아엎으면 못 잡지만, 그건 실제로 안내를 안 한 것이 맞다.
_KEY_PHRASE = "모티만기억"


def opening_notice(name: str | None) -> str:
    """대화 시작 안내(이름을 알게 된 직후 한 번)."""
    return OPENING_NOTICE.format(name=name) if name else OPENING_NOTICE_NO_NAME


def closing_notice(name: str | None) -> str:
    """대화 종료 안내([대화종료] 직전 한 번)."""
    return CLOSING_NOTICE.format(name=name) if name else CLOSING_NOTICE_NO_NAME


def was_delivered(spoken_text: str | None) -> bool:
    """한 턴에서 실제로 발화된 텍스트에 안내 멘트가 들어있는지."""
    if not spoken_text:
        return False
    return _KEY_PHRASE in "".join(spoken_text.split())


def opening_prompt(name: str | None) -> str:
    """이름을 알게 된 직후 주입할 히든 턴 — 정확한 문장을 그대로 말하게 한다."""
    return (
        "(진행자 지시: 지금 이 시점에 반드시 아래 안내를 해야 합니다. 앞뒤로 다른 말을 덧붙이지 말고, "
        "아래 문장을 토씨 하나 바꾸지 말고 그대로 소리 내어 말하세요. 이 지시 자체는 절대 언급하지 마세요.)\n"
        f"{opening_notice(name)}"
    )


def closing_prompt(name: str | None) -> str:
    """[대화종료] 턴에 안내가 빠졌을 때 한 번 더 시키는 히든 턴.

    이 턴을 끝으로 세션이 닫히므로 `[대화종료]` 태그를 다시 붙이라고 하지 않는다 —
    태그는 이미 launcher.py가 감지했고, 다시 붙이면 대화록에 두 번 남는다.
    """
    return (
        "(진행자 지시: 작별 인사에 필수 안내가 빠졌습니다. 다른 말을 덧붙이지 말고 아래 문장만 "
        "그대로 소리 내어 말하고 대화를 마치세요. 이 지시 자체는 절대 언급하지 마세요. "
        "[대화종료] 태그는 다시 붙이지 마세요.)\n"
        f"{closing_notice(name)}"
    )


def persona_instruction_block() -> str:
    """시스템 인스트럭션에 넣을 지시문.

    Python이 히든 턴으로 강제하긴 하지만, 페르소나에도 같은 지시를 넣어두면 모델이 자발적으로
    제때 말해서 히든 턴 주입 자체가 불필요해지는 경우가 많다(주입은 대화 흐름을 한 번 끊으므로
    안 쓰는 편이 자연스럽다). **실험 모드(QUIZ_EXPERIMENT_MODE)에서도 절대 빼지 않는다** —
    이 멘트는 측정 대상 그 자체다.
    """
    return f"""    # [필수 안내 멘트 — 신뢰 고지] 🚨 아래 두 번은 반드시, 정확히 이 문장으로 말해야 합니다.
    1. 🚨**`remember_fact`로 이름을 실제로 저장한 바로 그 턴에만** (이미 이름을 알고 있는 사람이면 첫 인사 직후에) — 다른 말을 길게 덧붙이지 말고 이렇게 안내하세요:
       "{OPENING_NOTICE.format(name='<상대 이름>')}"
       🚨**이름을 되묻는 확인 턴("OOO님, 맞을까요?")에서는 절대 말하지 마세요.** 안내는 저장이 끝난 뒤입니다.
       🚨**세션당 한 번뿐입니다.** 이름을 잘못 들어 다시 확인했거나 이름이 정정됐더라도, 이미 한 번 안내했다면 다시 말하지 마세요.
    2. 대화를 마치며 작별 인사를 할 때(`[대화종료]` 태그를 붙이는 그 턴), 작별 인사와 함께 이렇게 말하세요:
       "{CLOSING_NOTICE.format(name='<상대 이름>')}"
    - 이 두 문장은 연구상 모든 참가자가 똑같이 들어야 하므로, 표현을 바꾸거나 요약하거나 생략하지 마세요.
    - 단, "안내사항이 있습니다"를 대화 도중 아무 때나 반복하지는 마세요 — 위 두 시점에만, 각각 한 번씩만 말합니다."""
